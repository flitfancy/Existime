"""Generate the firmware wiring/order from the identified live PCB readback."""
import csv
import json
import math
from pathlib import Path

root = Path(__file__).resolve().parent
d = json.loads((root/'design-evidence.json').read_text(encoding='utf-8-sig'))
assert d['success'] and d['result']['project'] == 'e5cf8ab034eb4bb19c06c0800e697e85'
assert d['result']['pcb'] == '9da6d699202ca91c'
parts = {x['ref']: x for x in d['result']['parts']}
pins = lambda ref: {x['pin']: x['net'] for x in parts[ref]['pins']}
assert pins('SW2') == {'1':'KEY_SET','2':'GND'}
assert pins('SW1') == {'1':'KEY_NEXT','2':'GND'}
assert pins('U1')['7'] == 'KEY_NEXT' and pins('U1')['8'] == 'KEY_SET'
assert pins('SW3')['2'] == 'SYS_EN'
assert set(pins('R3').values()) == {'VDD_3V3','LED_A35'}
drivers = {}
for i in range(5):
    for port, pin in enumerate(['4','5','6','7','9','10','11','12']):
        net = pins(f'U{i+4}')[pin]
        assert net.startswith('LED_K')
        n = int(net[5:])
        assert n not in drivers
        drivers[n] = (i, port)
for n, pin in [(7,6),(8,7),(43,8)]:
    assert n not in drivers
    drivers[n] = (5, pin)
assert set(drivers) == set(range(1,44))
center = parts['D43']
for n in range(35,43):
    assert drivers[n] == (0,n-35), 'Direction PWM requires the dedicated 0x20 expander'
    led=parts[f'D{n}']
    angle=math.degrees(math.atan2(led['x']-center['x'],led['y']-center['y']))%360
    assert abs((angle-(n-35)*45+180)%360-180)<0.1, (n,angle)
province = sorted(range(1,35), key=lambda n:(parts[f'D{n}']['x'], -parts[f'D{n}']['y'], n))
lines = ['/* Generated by generate_board.py from design-evidence.json. */',
         '#ifndef BOARD_GENERATED_H', '#define BOARD_GENERATED_H',
         '#define PROVINCE_COUNT 34', 'struct led_driver { unsigned char device, bit; };',
         'static const struct led_driver led_drivers[44] = { {0,0},']
for n in range(1,44):
    lines.append('    {%d,%d}, /* D%d */' % (*drivers[n],n))
lines += ['};', 'static const unsigned char province_order[34] = {'+','.join(map(str,province))+'};', '#endif']
(root/'board_generated.h').write_text('\n'.join(lines)+'\n',encoding='utf-8')
with (root/'province-order.csv').open('w',newline='',encoding='utf-8-sig') as f:
    w=csv.writer(f); w.writerow(['index','LED','PCB_X_mil','PCB_Y_mil','driver','bit'])
    for i,n in enumerate(province):
        p=parts[f'D{n}'];dev,bit=drivers[n]
        w.writerow([i,f'D{n}',p['x'],p['y'],f'0x{0x20+dev:02X}' if dev<5 else 'GPIOA',bit])
print('34 province LEDs, X ascending:',province)
